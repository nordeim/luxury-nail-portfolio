export function productBySlug(slug: string, catalog: Product[]): Product | undefined {
  return catalog.find((product) => product.slug === slug);
}

export function productById(id: string, catalog: Product[]): Product | undefined {
  return catalog.find((product) => product.id === id);
}

export function relatedProducts(product: Product, catalog: Product[]): Product[] {
  return catalog.filter(
    (item) => item.visible && item.category === product.category && item.id !== product.id,
  );
}
